/**
 * Generates the bundled Google OAuth client module.
 *
 * The desktop client's secret is non-confidential by Google's own model for
 * installed apps, but GitHub's push protection still flags it, so it must not
 * live in the repository. CI injects the values from repository secrets and
 * this script bakes them into the published build.
 *
 * Run with no env vars (local development) and it writes empty strings, which
 * simply means Google sign-in falls back to whatever the user configures.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.resolve(here, '../src/generated');
const outFile = path.join(outDir, 'google-client.ts');

const clientId = process.env.SCYNC_GOOGLE_CLIENT_ID || process.env.VITE_GOOGLE_CLIENT_ID || '';
const clientSecret =
  process.env.SCYNC_GOOGLE_CLIENT_SECRET || process.env.VITE_GOOGLE_CLIENT_SECRET || '';

if (!clientId && process.env.CI) {
  console.warn(
    '[generate-google-client] SCYNC_GOOGLE_CLIENT_ID is not set; the published build will not bundle Google sign-in.'
  );
}

const source = `// Generated by scripts/generate-google-client.mjs — do not edit.
export const BUNDLED_GOOGLE_CLIENT_ID = ${JSON.stringify(clientId)};
export const BUNDLED_GOOGLE_CLIENT_SECRET = ${JSON.stringify(clientSecret)};
`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, source, 'utf8');
